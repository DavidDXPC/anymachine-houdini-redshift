def lookup(name, asset, fixtures):
    group = "fixture" if asset in fixtures else "equipment"
    entries = PALETTE.get(asset, {})
    key = name.removesuffix("_t")
    row = entries.get(name, entries.get(key))
    if row is None:
        row = PALETTE[group].get(key, PALETTE["fixture"].get(key))
    if row is None:
        row = next((values[name] for values in PALETTE.values() if name in values), None)
    if row is None:
        raise KeyError(name)
    values = dict(base=row[:3], metal=row[3], rough=row[4])
    if name.startswith("lit_") and name[4:] in LIT:
        light = LIT[name[4:]]
        values.update(emission=light["rgb"], emission_weight=light["strength"])
    if name == "window_glass":
        values["transmission"] = 1.0
    values["base"] = _acescg(values["base"])
    if "emission" in values:
        values["emission"] = _acescg(values["emission"])
    return values


# Linear Rec.709 D65 to ACEScg AP1 D60 with Bradford white-point adaptation.
_TO_ACESCG = (
    (0.613097402, 0.339523146, 0.047379451),
    (0.070193722, 0.916353879, 0.013452398),
    (0.020615593, 0.109569773, 0.869814634),
)


def _acescg(color):
    return tuple(sum(a*b for a,b in zip(row,color)) for row in _TO_ACESCG)
